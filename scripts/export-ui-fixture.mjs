// Write test/fixtures/ui-vcs.sql from the VC facts in local D1 (or --remote):
// investors, their team, investments, and the companies with their rounds
// and financials. Load it with `npm run db:seed:ui`.
import { writeFileSync } from 'node:fs';
import { parseArgs } from 'node:util';
import { sqlLiteral, wranglerD1 } from './dealroom-pull.mjs';

const { values } = parseArgs({ options: { remote: { type: 'boolean', default: false } } });
const d1 = wranglerD1({ remote: values.remote });
// raw_json is the full Dealroom record, which the UI doesn't read; '{}' keeps the fixture small.
const slim = row => ('raw_json' in row ? { ...row, raw_json: '{}' } : row);
const insert = (table, rows) => rows.map(slim).map(row => `INSERT INTO ${table} (${Object.keys(row).join(', ')}) VALUES (${Object.values(row).map(sqlLiteral).join(', ')});`);
const portfolio = 'SELECT company_uuid FROM investments';
try {
  const tables = {
    investors: await d1.query('SELECT * FROM investors WHERE uuid IN (SELECT investor_uuid FROM investments) ORDER BY name'),
    companies: await d1.query(`SELECT * FROM companies WHERE uuid IN (${portfolio}) ORDER BY name`),
    company_financials: await d1.query(`SELECT * FROM company_financials WHERE company_uuid IN (${portfolio}) ORDER BY company_uuid, year`),
    funding_rounds: await d1.query(`SELECT * FROM funding_rounds WHERE company_uuid IN (${portfolio}) ORDER BY company_uuid, id`),
    investments: await d1.query('SELECT * FROM investments ORDER BY investor_uuid, company_uuid'),
    investor_team: await d1.query('SELECT * FROM investor_team WHERE investor_uuid IN (SELECT investor_uuid FROM investments) ORDER BY investor_uuid, name')
  };
  const lines = [
    `-- ${tables.investors.length} real UK and Spanish VC firms from Dealroom with their team, and the ${tables.companies.length} UK and Spanish`,
    '-- portfolio companies they hold, with funding rounds and filed financials. Facts only: which companies match',
    '-- is decided by the profile criteria. Generated by scripts/export-ui-fixture.mjs.',
    '-- Load with `npm run db:seed:ui`. It replaces local leads, companies and VC data; never run it against remote D1.',
    ...['leads', 'investments', 'investor_team', 'company_financials', 'funding_rounds', 'investors', 'companies'].map(table => `DELETE FROM ${table};`),
    ...Object.entries(tables).flatMap(([table, rows]) => insert(table, rows))
  ];
  writeFileSync(new URL('../test/fixtures/ui-vcs.sql', import.meta.url), `${lines.join('\n')}\n`);
  console.log(Object.entries(tables).map(([table, rows]) => `${table} ${rows.length}`).join(', '));
} finally { d1.close(); }
