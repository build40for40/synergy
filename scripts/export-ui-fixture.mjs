// Write test/fixtures/ui-vcs.sql from the VC leads in local D1 (or --remote):
// every investor with matches, its partners, its matches and their companies.
// Load it with `npm run db:seed:ui`.
import { writeFileSync } from 'node:fs';
import { parseArgs } from 'node:util';
import { sqlLiteral, wranglerD1 } from './dealroom-pull.mjs';

const { values } = parseArgs({ options: { remote: { type: 'boolean', default: false } } });
const d1 = wranglerD1({ remote: values.remote });
const insert = (table, rows) => rows.map(row => `INSERT INTO ${table} (${Object.keys(row).join(', ')}) VALUES (${Object.values(row).map(sqlLiteral).join(', ')});`);
try {
  const investors = await d1.query('SELECT * FROM investors WHERE uuid IN (SELECT investor_uuid FROM portfolio_matches) ORDER BY name');
  const partners = await d1.query('SELECT * FROM investor_partners WHERE investor_uuid IN (SELECT investor_uuid FROM portfolio_matches) ORDER BY investor_uuid, name');
  const matches = await d1.query('SELECT * FROM portfolio_matches ORDER BY investor_uuid, company_uuid');
  const companies = await d1.query('SELECT * FROM companies WHERE uuid IN (SELECT company_uuid FROM portfolio_matches) ORDER BY name');
  const lines = [
    `-- ${investors.length} real UK and Spanish VC firms from Dealroom, with their partners and the ${companies.length}`,
    '-- portfolio companies that match the brief. Generated by scripts/export-ui-fixture.mjs.',
    '-- Load with `npm run db:seed:ui`. It replaces local leads, companies and VC data; never run it against remote D1.',
    'DELETE FROM leads;', 'DELETE FROM portfolio_matches;', 'DELETE FROM investor_partners;', 'DELETE FROM investors;', 'DELETE FROM companies;',
    ...insert('investors', investors), ...insert('investor_partners', partners), ...insert('companies', companies), ...insert('portfolio_matches', matches)
  ];
  writeFileSync(new URL('../test/fixtures/ui-vcs.sql', import.meta.url), `${lines.join('\n')}\n`);
  console.log(`${investors.length} VCs, ${partners.length} partners, ${companies.length} companies, ${matches.length} matches.`);
} finally { d1.close(); }
